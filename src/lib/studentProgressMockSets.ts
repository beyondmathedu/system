export function mockSetSortKey(label: string): string {
  if (label.trim().toLowerCase() === "others") return "\uffff";
  const code = /^\(Set\s+([^)]+)\)/i.exec(label)?.[1]?.trim() ?? label;
  return code.toUpperCase();
}

export function sortMockSetLabels(labels: readonly string[]): string[] {
  return [...labels].sort((a, b) =>
    mockSetSortKey(a).localeCompare(mockSetSortKey(b), "en", { numeric: true, sensitivity: "base" }),
  );
}

/** Trim, drop blanks, keep first of each exact label, then A–Z (Others last). */
export function normalizeMockSetLabels(raw: unknown): string[] {
  if (!Array.isArray(raw)) return [];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of raw) {
    const label = String(item ?? "").trim();
    if (!label || seen.has(label)) continue;
    seen.add(label);
    out.push(label);
  }
  return sortMockSetLabels(out);
}

